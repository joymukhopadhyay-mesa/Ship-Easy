// Corrected workbook in the official template structure (title row 1, header row 2,
// grey example row 3, data from row 4), plus the fixed Sheets 3/4 and a results sheet.
import * as XLSX from "xlsx";
import carriers from "@/data/carriers.json";
import rulebook from "@/data/rulebook.json";
import { toDDMMYYYY } from "./dates";
import type { BookingResult } from "./types";

const BH = ["Booking ID", "Seller name", "Origin city", "Origin country", "Destination city", "Destination country", "Destination type", "Ready to ship date", "Seller priority", "Pallets", "Cartons", "Total declared value", "Currency", "Total gross weight (kg)", "Delivery appointment booked"];
const IH = ["Booking ID", "SKU", "Description", "HS code", "Quantity (units)", "Unit price", "Units per carton", "Cartons", "Unit weight (kg)", "Country of origin"];
const EXB = ["BK-001", "Northfield Goods", "Manchester", "United Kingdom", "Frankfurt", "Germany", "Warehouse", "05-11-2026", "Cheapest", 3, 90, 5400, "GBP", 620, "Yes"];
const EXI = ["BK-001", "MUG-01", "Ceramic coffee mug, 350 ml", 691200, 1080, 5, 12, 90, 0.5, "United Kingdom"];

export function correctedWorkbook(results: BookingResult[]): ArrayBuffer {
  const anyOverride = results.some((r) => r.booking.chosenCarrier);
  const bh = anyOverride ? [...BH, "Chosen carrier"] : BH;
  const bRows = results.map(({ booking: b }) => {
    const row: (string | number | null)[] = [b.bookingId, b.sellerName, b.originCity, b.originCountry, b.destinationCity, b.destinationCountry, b.destinationType,
      toDDMMYYYY(b.readyDate), b.priority, b.pallets, b.cartons, b.declaredValue, b.currency, b.grossWeight, b.appointmentBooked == null ? null : b.appointmentBooked ? "Yes" : "No"];
    if (anyOverride) row.push(b.chosenCarrier ? `Carrier ${b.chosenCarrier}` : null);
    return row;
  });
  const iRows = results.flatMap(({ booking: b }) => b.items.map((i) => [b.bookingId, i.sku, i.description, i.hsCode, i.quantity, i.unitPrice, i.unitsPerCarton, i.cartons, i.unitWeight, i.countryOfOrigin]));
  const wb = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([["Bookings — one row per record. Row 3 is an example (grey); enter data from row 4."], bh, EXB, ...bRows]), "Bookings");
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([["Items — one row per record. Row 3 is an example (grey); enter data from row 4."], IH, EXI, ...iRows]), "Items");
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
    ["FIXED - judges will use exactly this rate card. Do not edit."],
    ["Carrier", "Service", "Origin country", "Destination country", "Price per pallet", "Currency", "Transit time (days)", "On-time rate (%)", "Max weight per pallet (kg)"],
    ...carriers.carriers.map((c) => [c.carrier, c.service, c.originCountry, c.destinationCountry, c.pricePerPallet, c.currency, c.transitDays, c.onTimePct, c.maxKgPerPallet]),
  ]), "Carrier options");
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
    ["FIXED - these are the only rules judges will test against. Do not edit."],
    ["Rule ID", "Rule", "Severity if broken"],
    ...rulebook.rules.map((r) => [r.id, r.text, r.severity]),
  ]), "Rulebook");
  XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([
    ["Pre-flight results (generated by PreFlight)"],
    ["Booking ID", "Verdict", "Failing checks", "Recommended carrier", "Chosen carrier", "Total cost (GBP)", "Collection", "ETA"],
    ...results.map((r) => {
      const c = r.carrier;
      const o = c.options.find((x) => x.id === c.chosen);
      return [r.booking.bookingId, r.verdict, r.rules.filter((x) => x.status === "fail").map((x) => `${x.id} ${x.severity}`).join(", ") || "none",
        c.recommended ? `Carrier ${c.recommended}` : "none", c.chosen ? `Carrier ${c.chosen}` : "none", o?.totalCost ?? null, toDDMMYYYY(c.dates.collection), toDDMMYYYY(c.dates.eta)];
    }),
  ]), "Pre-flight results");
  return XLSX.write(wb, { type: "array", bookType: "xlsx" }) as ArrayBuffer;
}
